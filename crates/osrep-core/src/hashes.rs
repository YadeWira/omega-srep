//! Unkeyed digests stored per block: MD5, SHA-1 and SHA-512.
//!
//! Rust port of the `compute_md5` / `compute_sha1` / `compute_sha512`
//! wrappers in `Compression/SREP/hashes.cpp` (which drive the vendored
//! LibTomCrypt sources). The algorithms are standard, but the vendored
//! copies carry local patches, so `tests/rust_conformance.sh` diffs the
//! output against the C++ binary rather than trusting test vectors alone.
//!
//! All three take no seed and produce a fixed-size digest. The keyed
//! hashes (`vmac`, `siphash`) live in `hashes_keyed`.

pub const MD5_SIZE: usize = 16;
pub const SHA1_SIZE: usize = 20;
pub const SHA512_SIZE: usize = 64;

