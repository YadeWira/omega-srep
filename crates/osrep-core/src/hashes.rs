const SHA512_H0: [u64; 8] = [
    0x6a09e667f3bcc908, 0xbb67ae8584caa73b, 0x3c6ef372fe94f82b, 0xa54ff53a5f1d36f1,
    0x510e527fade682d1, 0x9b05688c2b3e6c1f, 0x1f83d9abfb41bd6b, 0x5be0cd19137e2179,
];

pub fn sha512(data: &[u8]) -> [u8; SHA512_SIZE] {
    let mut h = SHA512_H0;
    for block in padded_blocks_be128(data) {
        let mut w = [0u64; 80];
        for i in 0..16 {
            let mut b = [0u8; 8];
            b.copy_from_slice(&block[8 * i..8 * i + 8]);
            w[i] = u64::from_be_bytes(b);
        }
        for i in 16..80 {
            let s0 = w[i - 15].rotate_right(1) ^ w[i - 15].rotate_right(8) ^ (w[i - 15] >> 7);
            let s1 = w[i - 2].rotate_right(19) ^ w[i - 2].rotate_right(61) ^ (w[i - 2] >> 6);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let (mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh) =
            (h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
        for i in 0..80 {
            let s1 = e.rotate_right(14) ^ e.rotate_right(18) ^ e.rotate_right(41);
            let ch = (e & f) ^ (!e & g);
            let t1 = hh
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(SHA512_K[i])
                .wrapping_add(w[i]);
            let s0 = a.rotate_right(28) ^ a.rotate_right(34) ^ a.rotate_right(39);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            hh = g;
            g = f;
            f = e;
            e = d.wrapping_add(t1);
            d = c;
            c = b;
            b = a;
            a = t1.wrapping_add(t2);
        }
        let add = [a, b, c, d, e, f, g, hh];
        for (slot, v) in h.iter_mut().zip(add.iter()) {
            *slot = slot.wrapping_add(*v);
        }
    }

    let mut out = [0u8; SHA512_SIZE];
    for (i, v) in h.iter().enumerate() {
        out[8 * i..8 * i + 8].copy_from_slice(&v.to_be_bytes());
    }
    out
}

// ------------------------------------------------------------ padding --

/// MD5 padding: `1` bit, zeros, then the length in bits as a 64-bit
/// little-endian trailer.
fn padded_blocks_le(data: &[u8], block_size: usize) -> Vec<[u8; 64]> {
    let mut msg = data.to_vec();
    let bits = (data.len() as u64).wrapping_mul(8);
    msg.push(0x80);
    while msg.len() % block_size != block_size - 8 {
        msg.push(0);
    }
    msg.extend_from_slice(&bits.to_le_bytes());
    to_blocks(&msg)
}

/// SHA-1/SHA-512 padding: `1` bit, zeros, then the length in bits as a
/// 64-bit big-endian trailer.
fn padded_blocks_be(data: &[u8], block_size: usize) -> Vec<[u8; 64]> {
    let mut msg = data.to_vec();
    let bits = (data.len() as u64).wrapping_mul(8);
    msg.push(0x80);
    while msg.len() % block_size != block_size - 8 {
        msg.push(0);
    }
    msg.extend_from_slice(&bits.to_be_bytes());
    to_blocks(&msg)
}

/// SHA-512 pads with a 128-bit big-endian length at the end of a 128-byte
/// block.
fn padded_blocks_be128(data: &[u8]) -> Vec<[u8; 128]> {
    let mut msg = data.to_vec();
    let bits = (data.len() as u128).wrapping_mul(8);
    msg.push(0x80);
    while msg.len() % 128 != 112 {
        msg.push(0);
    }
    msg.extend_from_slice(&bits.to_be_bytes());
    let mut blocks = Vec::with_capacity(msg.len() / 128);
    for chunk in msg.chunks_exact(128) {
        let mut b = [0u8; 128];
        b.copy_from_slice(chunk);
        blocks.push(b);
    }
    blocks
}

fn to_blocks(msg: &[u8]) -> Vec<[u8; 64]> {
    let mut blocks = Vec::with_capacity(msg.len() / 64);
    for chunk in msg.chunks_exact(64) {
        let mut b = [0u8; 64];
        b.copy_from_slice(chunk);
        blocks.push(b);
    }
    blocks
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(bytes: &[u8]) -> String {
        bytes.iter().map(|b| format!("{b:02x}")).collect()
    }

    #[test]
    fn known_answer_vectors() {
        // FIPS 180-4 / RFC 1321 vectors for "abc".
        assert_eq!(hex(&md5(b"abc")), "900150983cd24fb0d6963f7d28e17f72");
        assert_eq!(hex(&sha1(b"abc")), "a9993e364706816aba3e25717850c26c9cd0d89d");
        assert_eq!(
            hex(&sha512(b"abc")),
            "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a\
             2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f"
        );
        // Empty input, and the two standard long-message vectors.
        assert_eq!(hex(&sha1(b"")), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
        assert_eq!(hex(&md5(b"")), "d41d8cd98f00b204e9800998ecf8427e");
        assert_eq!(
            hex(&sha1(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")),
            "84983e441c3bd26ebaae4aa1f95129e5e54670f1"
        );
        assert_eq!(
            hex(&sha1(&vec![b'a'; 1_000_000])),
            "34aa973cd4c4daa4f61eeb2bdbad27316534016f"
        );
    }
}
